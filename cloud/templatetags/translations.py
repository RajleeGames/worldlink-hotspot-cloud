@register.simple_tag(takes_context=True)
def t(context,phrase):
    request=context.get('request')
    language=request.session.get('ui_lang','en') if request else 'en'
    return SW.get(phrase,phrase) if language=='sw' else phrase

@register.simple_tag(takes_context=True)
def query_page(context, number):
    request = context.get('request')
    if not request:
        return f'?page={int(number)}'
    params = request.GET.copy()
    params['page'] = str(int(number))
    return '?' + params.urlencode()
